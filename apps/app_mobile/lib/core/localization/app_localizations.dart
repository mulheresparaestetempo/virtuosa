class AppLocalizations {
  static const supportedLocales = [
    Locale('pt', 'BR'),
    Locale('en', 'US'),
    Locale('es', 'ES'),
  ];

  static String translate(String key, Locale locale, {Map<String, String>? params}) {
    final languageCode = locale.languageCode;
    String text = localizations[languageCode]?[key] ?? localizations['pt']![key] ?? key;

    if (params != null) {
      params.forEach((key, value) {
        text = text.replaceAll('{$key}', value);
      });
    }

    return text;
  }
}
